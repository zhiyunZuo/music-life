  W.bindHistory = function () {
    const view = document.getElementById("view");
    if (!view) return;
    const body = document.getElementById("hist-body");
    view.querySelectorAll(".itab[data-htb]").forEach(b => {
      b.onclick = () => {
        view.querySelectorAll(".itab[data-htb]").forEach(x => x.classList.remove("on"));
        b.classList.add("on");
        const t = b.dataset.htb;
        ["eras","figs","events","inst"].forEach(k => {
          const el = document.getElementById("hist-"+k);
          if (el) el.style.display = (k === t) ? "" : "none";
        });
        if (body) body.style.display = (t === "today") ? "" : "none";
        if (t === "figs") {
          view.querySelectorAll(".fig-row[data-fig]").forEach(r => {
            r.onclick = () => {
              const f = W.figureOf(r.dataset.fig);
              if (!f) return;
              body.innerHTML = `<div class="panel"><div class="sec-tag">人物档案</div>${W.figureCardHTML(f, true)}</div>`;
              body.style.display = "";
              const fe = document.getElementById("hist-figs");
              if (fe) fe.style.display = "none";
            };
          });
        }
      };
    });
  };
